function viewLegal(kind) {
  const page = LEGAL[kind];
  app.innerHTML = `<article class="legal">
    <h1>${page.title}</h1>
    <p class="muted">Действует с ${esc(SELLER.updated)} · ${esc(SELLER.domain)}</p>
    ${legalIncomplete() ? '<div class="panel" style="border-color:var(--warn);margin-bottom:18px">⚠ Реквизиты продавца ещё не заполнены. Владелец сайта должен вписать их в <code>public/js/legal.js</code>.</div>' : ''}
    <div class="panel legal-body">${page.html()}</div>
    <p class="muted" style="margin-top:14px">Другие документы:
      ${Object.entries(LEGAL).filter(([k]) => k !== kind).map(([k, v]) => `<a href="#/${k}" style="color:var(--gold-2)">${v.title}</a>`).join(' · ')}</p>
  </article>`;
}

// Информационное уведомление (cookies только необходимые — согласие не нужно, но сообщить честно)
function cookieNotice() {
  let seen = false;
  try { seen = localStorage.getItem('sf_cookie_ok') === '1'; } catch { /* приватный режим */ }
  if (seen) return;
  const bar = document.createElement('div');
  bar.className = 'cookie-bar';
  bar.innerHTML = `<span>Мы используем только необходимые cookies: для входа в аккаунт и корзины. Без рекламы и слежки.
    <a href="#/cookies">Подробнее</a></span><button class="btn sm primary">Понятно</button>`;
  bar.querySelector('button').addEventListener('click', () => {
    try { localStorage.setItem('sf_cookie_ok', '1'); } catch { /* ничего */ }
    bar.remove();
  });
  document.body.append(bar);
}
